"""Expand cluster/plan_v1.json into a job list for one tier (the cluster agent picks the tier; plan §1/§8).
Each job is one shell command; jobs are grouped so that one process handles all arms that share a block size (the
block size is a process-wide setting), and one prepared data directory is shared by all arms of a (model, length).
Arms whose status is not "ready" are skipped with a warning, never silently. After each data preparation the frozen
unit-length file (cluster/unit_lengths.py, plan coverage_rule) is written next to the data for every block in use.
Nothing is run here.
Usage: make_jobs.py --tier {1,2,3} --models-dir DIR --out-root DIR [--gpu48] [--project-py PY] [--ruler-root DIR]
       [--ruler-venv DIR] > jobs.sh      (review it, then run it; or pass --dry_run to print a summary only)"""
import argparse
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", required=True, choices=["1", "2", "3"])
    ap.add_argument("--models-dir", required=True, help="directory holding one folder per model (HF snapshot)")
    ap.add_argument("--out-root", required=True)
    ap.add_argument("--gpu48", action="store_true", help="tier 3 on a 48GB card: add the 32k length")
    ap.add_argument("--project-py", default=sys.executable)
    ap.add_argument("--ruler-root", default="/opt/ruler")
    ap.add_argument("--ruler-venv", default="")
    ap.add_argument("--dry_run", action="store_true")
    a = ap.parse_args()
    plan = json.load(open(os.path.join(HERE, "plan_v1.json")))
    tier = plan["tiers"][a.tier]
    lengths = list(tier["lengths"]) + (tier.get("lengths_48gb_extra", []) if a.gpu48 else [])
    arms = []
    for name in tier["arms"]:
        arm = plan["arms"][name]
        if arm["status"] != "ready":
            print(f"# SKIP arm {name}: {arm['status']}", file=sys.stderr)
            continue
        arms.append((name, arm))
    lines, n_pred = ["#!/usr/bin/env bash", f"# generated by cluster/make_jobs.py --tier {a.tier}", "set -u"], 0
    for mkey in tier["models"]:
        model = plan["models"][mkey]
        mdir = os.path.join(a.models_dir, mkey)
        for L in lengths:
            data = os.path.join(a.out_root, "data", mkey, str(L))
            env = (f"RULER_ROOT={shlex.quote(a.ruler_root)} RULER_TOKENIZER={shlex.quote(mdir)} "
                   f"RULER_TEMPLATE={model['template']} PROJECT_PY={shlex.quote(a.project_py)} CPU_SET="
                   + (f" RULER_VENV={shlex.quote(a.ruler_venv)}" if a.ruler_venv else ""))
            lines.append(f"\n# ---- {mkey} @ {L}: prepare {plan['prepared_samples']} samples/task (frozen)")
            lines.append(f"{env} bash {ROOT}/scripts/ruler_prepare.sh {L} {plan['prepared_samples']} {data} "
                         f"|| exit 1")
            cr = plan["coverage_rule"]                # frozen with the data, before any prediction (plan §3.4)
            for blk in sorted({arm["block"] for _, arm in arms if arm["block"]}):
                lines.append(f"{shlex.quote(a.project_py)} {ROOT}/cluster/unit_lengths.py --data-dir {data} "
                             f"--tokenizer {shlex.quote(mdir)} --n {plan['prepared_samples']} --block {blk} "
                             f"--local {cr['local']} --unit {cr['unit']} --json {data}/unit_lengths_b{blk}.json || exit 1")
            for bud in tier["budgets"]:
                pc = plan["primary_cell"]
                n = pc["samples"] if (mkey, L, bud) == (pc["model"], pc["length"], pc["budget"]) else tier["samples_other"]
                tag = f"t{a.tier}_n{n}"          # run tag: different tiers/sample counts never share a directory
                lines.append(f"# {mkey} @ {L}, budget {bud}: predict on frozen line numbers 0..{n - 1} (run tag {tag})")
                by_block = {}
                for name, arm in arms:
                    by_block.setdefault(arm["block"], []).append(arm["method"])
                for block, methods in sorted(by_block.items()):
                    for task in plan["tasks"]:
                        pred = os.path.join(a.out_root, "pred", mkey, str(L), f"budget{bud}", f"b{block}", tag)
                        lines.append(
                            f"{shlex.quote(a.project_py)} {ROOT}/src/ruler_pred.py --ruler {shlex.quote(a.ruler_root)} "
                            f"--model {shlex.quote(mdir)} --data_dir {data} --save_dir {pred} --task {task} "
                            f"--methods {','.join(sorted(set(methods)))} --budget {bud} --block {block} "
                            f"--limit {n} --strict-budget || exit 1")
                        n_pred += 1
    if a.dry_run:
        print(f"tier {a.tier}: models {tier['models']}, lengths {lengths}, budgets {tier['budgets']}, "
              f"arms {[n for n, _ in arms]}; prediction jobs {n_pred}")
        return
    print("\n".join(lines))


if __name__ == "__main__":
    main()
