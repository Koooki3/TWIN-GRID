"""Expand cluster/plan_v2.json (frozen 2026-10-19) into a job script for one tier. Nothing is run here.
Differences from the frozen v1.4 generator (cluster/make_jobs.py, unchanged):
  --phase prep     data preparation, the n = 200 unit-length file (B = 32), the memory probe of the primary cell for
                   every block, the adapter acceptance (cluster/accept_adapter.py + accept_tie_diag.py + accept_ties.py,
                   docs/CLUSTER_GUIDE_ZH.md §3; its verdict line saved to <out-root>/accept/<model>.verdict.txt and the
                   strict report to <model>.report.json), and finally cluster/v2_run_descriptor.py register, which
                   refuses unless the full weight set (all index shards), the 40-hex revision and HF repo, ACCEPTED
                   adapter verdict and probes with >= 10% headroom on the actual device are present. The descriptor
                   is the structured tier record (Codex implementation review I2); plan §8 gets its sha256.
  --phase predict  needs --rd (the registered descriptor); takes the revision from it; the script's first command is
                   v2_run_descriptor.py verify (re-hashes every weight file, data, unit file, plan and code; exit 1 on
                   any difference) and every prediction command is followed by v2_run_descriptor.py bind (sidecar
                   binding of the manifest and prediction files to the descriptor).
  Calibration rows: src/ruler_pred.py (frozen) only has --limit, so calibration arms run --limit 200 on S_unit tasks
  (lines 0..99 main, 100..199 calibration); every other (arm, task) runs --limit 100; auxiliary cells run main rows.
One process per (block, limit, task) shares the prefill across the methods of that block.
Usage: make_jobs_v2.py --phase prep --tier T --model M --revision SHA40 --models-dir DIR --out-root DIR [...]
       make_jobs_v2.py --phase predict --tier T --rd RD.json --models-dir DIR --out-root DIR [...]
       common: [--project-py PY] [--ruler-root DIR] [--ruler-venv DIR] [--dry_run]"""
import argparse
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def expand(plan, tier_key):
    """Return list of (model, length, budget, block, limit, task, methods, role) prediction groups."""
    tier = plan["tiers"][tier_key]
    pc, s_unit = plan["primary_cell"], [t for t in plan["tasks"] if t not in plan["no_unit_tasks"]]
    out = []
    for m in tier["models"]:
        for L in tier["lengths"]:
            for bud in tier["budgets"]:
                primary = (m, L, bud) == (pc["model"], pc["length"], pc["budget"])
                calib = set(tier["calibration_arms"]) if primary else set()
                groups = {}
                for name in tier["arms"]:
                    arm = plan["arms"][name]
                    for t in plan["tasks"]:
                        lim = 200 if (name in calib and t in s_unit) else 100
                        groups.setdefault((arm["block"], lim, t), set()).add(arm["method"])
                for (blk, lim, t), meths in sorted(groups.items()):
                    out.append((m, L, bud, blk, lim, t, sorted(meths), "primary-cell" if primary else "auxiliary"))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--phase", required=True, choices=["prep", "predict"])
    ap.add_argument("--tier", required=True, choices=["1", "2", "3"])
    ap.add_argument("--models-dir", required=True)
    ap.add_argument("--out-root", required=True)
    ap.add_argument("--model", default="", help="prep: model key")
    ap.add_argument("--revision", default="", help="prep: 40-hex HF commit of the snapshot")
    ap.add_argument("--rd", default="", help="predict: registered run descriptor")
    ap.add_argument("--project-py", default=sys.executable)
    ap.add_argument("--ruler-root", default="/opt/ruler")
    ap.add_argument("--ruler-venv", default="")
    ap.add_argument("--dry_run", action="store_true")
    a = ap.parse_args()
    plan = json.load(open(os.path.join(HERE, "plan_v2.json")))
    tier, pc, uf = plan["tiers"][a.tier], plan["primary_cell"], plan["unit_file"]
    groups = expand(plan, a.tier)
    py, q = shlex.quote(a.project_py), shlex.quote
    if a.dry_run:
        n_pred = sum(lim * len(me) for (_, _, _, _, lim, _, me, _) in groups)
        prim = sum(lim * len(me) for (_, _, _, _, lim, _, me, r) in groups if r == "primary-cell")
        print(f"tier {a.tier}: models {tier['models']}, lengths {tier['lengths']}, budgets {tier['budgets']}; "
              f"process groups {len(groups)}; predictions total {n_pred}, in the primary (model, length, budget) {prim}")
        return
    head = ["#!/usr/bin/env bash", f"# generated by cluster/make_jobs_v2.py --phase {a.phase} --tier {a.tier} "
            "(plan v2, frozen 2026-10-19)", "set -u"]
    desc = f"{py} {ROOT}/cluster/v2_run_descriptor.py"
    if a.phase == "prep":
        if a.model not in tier["models"] or len(a.revision) != 40:
            sys.exit("prep needs --model (in the tier) and a 40-hex --revision")
        m, model = a.model, plan["models"][a.model]
        mdir = q(os.path.join(a.models_dir, m))
        acc, probe = os.path.join(a.out_root, "accept"), os.path.join(a.out_root, "probe")
        lines = head + [f"mkdir -p {q(acc)} {q(probe)}"]
        for L in tier["lengths"]:
            data = os.path.join(a.out_root, "data", m, str(L))
            env = (f"RULER_ROOT={q(a.ruler_root)} RULER_TOKENIZER={mdir} RULER_TEMPLATE={model['template']} "
                   f"PROJECT_PY={py} CPU_SET=" + (f" RULER_VENV={q(a.ruler_venv)}" if a.ruler_venv else ""))
            lines += [f"\n# ---- {m} @ {L}: prepare {plan['prepared_samples']} samples/task (frozen), unit file n={uf['n']}",
                      f"{env} bash {ROOT}/scripts/ruler_prepare.sh {L} {plan['prepared_samples']} {data} || exit 1",
                      f"{py} {ROOT}/cluster/unit_lengths.py --data-dir {data} --tokenizer {mdir} --n {uf['n']} "
                      f"--block {uf['block']} --local {uf['local']} --unit {uf['unit']} "
                      f"--json {data}/unit_lengths_b32_n{uf['n']}.json || exit 1"]
        pdata = os.path.join(a.out_root, "data", m, str(pc["length"]))
        probes = []
        for blk in sorted({plan["arms"][n]["block"] for n in tier["arms"]}):
            meths = ",".join(sorted({plan["arms"][n]["method"] for n in tier["arms"] if plan["arms"][n]["block"] == blk}))
            pj = os.path.join(probe, f"{m}_{pc['length']}_b{blk}.json")
            probes.append(pj)
            lines.append(f"{py} {ROOT}/cluster/probe_memory.py --model {mdir} --length {pc['length']} --block {blk} "
                         f"--budget {pc['budget']} --methods {meths} --layout-unit 32 --json {q(pj)} || exit 1")
            lines.append(f"{desc} probe-receipt --probe {q(pj)} --tier {a.tier} --model {m} --models-dir {q(a.models_dir)} || exit 1")
        adata = os.path.join(acc, f"data_{m}")
        ac = plan["acceptance"]
        pred_acc, rep_p, ver_p = os.path.join(acc, "pred_" + m), os.path.join(acc, m + ".report.json"), \
            os.path.join(acc, m + ".verdict.txt")
        ev = f"{desc} eval-run --model {m} --models-dir {q(a.models_dir)}"
        envp = (f"RULER_ROOT={q(a.ruler_root)} RULER_TOKENIZER={mdir} RULER_TEMPLATE={model['template']} "
                f"PROJECT_PY={py} CPU_SET=" + (f" RULER_VENV={q(a.ruler_venv)}" if a.ruler_venv else ""))
        apred = (f"{py} {ROOT}/src/ruler_pred.py --ruler {q(a.ruler_root)} --model {mdir} --data_dir {q(adata)} "
                 f"--budget {pc['budget']} --block 32 --layout-unit 32 --strict-budget --model-revision {a.revision}")
        lines += [f"\n# ---- adapter acceptance (plan v1.4 §3.2, guide §5) on its own frozen data {adata} "
                  f"({ac['rows_per_task']} rows per task, every task); order / cache-isolation runs on {ac['order_task']} "
                  f"with --local {ac['order_local']} (generated tokens reach candidate blocks); predictions under "
                  f"{pred_acc}/ in the cluster/accept_adapter.py layout. Every evaluation runs through eval-run (inputs "
                  f"hashed before and after, output created by that run, provenance kept); an existing output is never "
                  f"overwritten: a new evaluation needs a new --out-root attempt.",
                  f"export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True",
                  f"{envp} bash {ROOT}/scripts/ruler_prepare.sh {pc['length']} {ac['rows_per_task']} {q(adata)} || exit 1"]
        for t in plan["tasks"]:
            lines.append(f"{apred} --save_dir {q(os.path.join(pred_acc, 'dense'))} --task {t} --methods dense || exit 1")
        for x, y in ac["pairs"]:
            tag = f"{x}__{y}"
            o = f"--task {ac['order_task']} --local {ac['order_local']}"
            lines += [f"{apred} --save_dir {q(os.path.join(pred_acc, 'order_ab_' + tag))} {o} --methods {x},{y} || exit 1",
                      f"{apred} --save_dir {q(os.path.join(pred_acc, 'order_ba_' + tag))} {o} --methods {y},{x} || exit 1",
                      f"{apred} --save_dir {q(os.path.join(pred_acc, 'single_' + x))} {o} --methods {x} || exit 1",
                      f"{apred} --save_dir {q(os.path.join(pred_acc, 'single_' + y))} {o} --methods {y} || exit 1"]
        lines += [f"{ev} --out {q(rep_p)} --watch {q(pred_acc)} --watch {q(adata)} -- {py} {ROOT}/cluster/accept_adapter.py "
                  f"--ruler {q(a.ruler_root)} --model {mdir} --data_dir {q(adata)} --tasks {','.join(plan['tasks'])} "
                  f"--pred_root {q(pred_acc)} --order_task {ac['order_task']} "
                  f"--pairs {','.join(x + ':' + y for x, y in ac['pairs'])} --budget {pc['budget']} --report {q(rep_p)}; true",
                  f"# one bf16 tie diagnostic per same-input mismatch (none if the acceptance is strict)",
                  f"{desc} tie-plan --report {q(rep_p)} --data-dir {q(adata)} --pred-root {q(pred_acc)} --ruler {q(a.ruler_root)} "
                  f"| while read K T LINE DATA PRED MAXNEW; do",
                  f"  {ev} --out {q(acc)}/{m}.tie_$K.json --watch {q(pred_acc)} --watch {q(adata)} -- {py} "
                  f"{ROOT}/cluster/accept_tie_diag.py {mdir} $DATA $LINE $PRED $MAXNEW {q(acc)}/{m}.tie_$K.json || exit 1",
                  f"done || exit 1",
                  f"TIES=$(for f in {q(acc)}/{m}.tie_*.json; do [ -e \"$f\" ] && printf -- '--adapter-tie-diag %q ' \"$f\"; done)",
                  f"{ev} --out {q(ver_p)} --stdout-to-out --watch {q(rep_p)} $(echo $TIES | sed 's/--adapter-tie-diag/--watch/g') "
                  f"-- {py} {ROOT}/cluster/accept_ties.py {q(rep_p)} $(echo $TIES | sed 's/--adapter-tie-diag//g') || exit 1",
                  f"# acceptance receipt right after the acceptance: report / verdict / ties bound to the complete inputs and "
                  f"the full model and code hashes",
                  f"{desc} accept-receipt --pred-root {q(os.path.join(acc, 'pred_' + m))} --data-dir {q(adata)} "
                  f"--order-task {ac['order_task']} --report {q(os.path.join(acc, m + '.report.json'))} "
                  f"--verdict {q(os.path.join(acc, m + '.verdict.txt'))} --model {m} --models-dir {q(a.models_dir)} "
                  f"$(echo $TIES | sed 's/--adapter-tie-diag/--tie-diag/g') || exit 1",
                  f"\n# ---- register the run descriptor (refuses on any missing or failing receipt)",
                  f"{desc} register --tier {a.tier} --model {m} --models-dir {q(a.models_dir)} --hf-repo {model['hf_id']} "
                  f"--revision {a.revision} --out-root {q(a.out_root)} --units {pdata}/unit_lengths_b32_n{uf['n']}.json "
                  f"--adapter-verdict {q(os.path.join(acc, m + '.verdict.txt'))} "
                  f"--adapter-report {q(os.path.join(acc, m + '.report.json'))} "
                  f"--adapter-pred-root {q(os.path.join(acc, 'pred_' + m))} --adapter-data-dir {q(adata)} $TIES "
                  + " ".join(f"--probe {q(p)}" for p in probes)
                  + f" --out {q(os.path.join(a.out_root, f'run_descriptor_t{a.tier}_{m}.json'))} || exit 1",
                  "echo 'prep done: record the descriptor sha256 in docs/PLAN_V2_SELECTION_RECORD_ZH.md, then generate --phase predict --rd ...'"]
        print("\n".join(lines))
        return
    if not a.rd:
        sys.exit("predict needs --rd (the registered run descriptor)")
    rd = json.load(open(a.rd))
    if rd.get("tier") != a.tier:
        sys.exit(f"descriptor tier {rd.get('tier')} != --tier {a.tier}")
    m, rev = rd["model"]["key"], rd["model"]["revision"]
    lines = head + [f"{desc} verify --rd {q(a.rd)} --models-dir {q(a.models_dir)} --out-root {q(a.out_root)} || exit 1"]
    for (gm, L, bud, blk, lim, t, meths, role) in groups:
        if gm != m:
            continue
        mdir = q(os.path.join(a.models_dir, gm))
        data = os.path.join(a.out_root, "data", gm, str(L))
        pred = os.path.join(a.out_root, "pred", gm, str(L), f"budget{bud}", f"b{blk}", f"t{a.tier}_n{lim}")
        lines.append(f"{py} {ROOT}/src/ruler_pred.py --ruler {q(a.ruler_root)} --model {mdir} --data_dir {data} "
                     f"--save_dir {pred} --task {t} --methods {','.join(meths)} --budget {bud} --block {blk} "
                     f"--layout-unit 32 --local 64 --limit {lim} --strict-budget --model-revision {rev} || exit 1   # {role}")
        lines.append(f"{desc} bind --rd {q(a.rd)} --save-dir {pred} --task {t} --methods {','.join(meths)} --budget {bud} || exit 1")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
