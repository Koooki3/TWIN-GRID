"""v1.4 APPENDIX jobs (descriptive only; docs/PLAN_V14_APPENDIX_ZH.md; reviewer batch 11, F2). The frozen
cluster/make_jobs.py is not modified; this script adds, for the PRIMARY CELL only (plan primary_cell: model, length,
budget, samples), the arms that reproduce the development conclusions on the cluster:
  group "sum"   (src/ruler_pred.py):  mean, mean+g2f, quest     -> summary type at equal memory (mean+g2f vs quest32)
  group "delim" (src/delim_dev.py):   cobs, cobs+g2f, delim_cobs -> delimiter chunking vs single grid and TWIN-GRID
Each group is one process per task with its own run tag (t<tier>_n<n>_appendix-sum / -delim), so its comparisons are
within one process and one manifest; compare with cluster/aggregate_appendix.py (all DESCRIPTIVE, no test). The data
directory is the one prepared (and unit-length-frozen) by the main jobs: run the main job script's preparation first.
B = 32, layout unit 32, the plan protocol flags; nothing else changes. Neighbour-read variants (nb/nbr/nbh) are not
included (worse than no expansion in every development group).
Usage: make_appendix_jobs.py --tier {1,2,3} --models-dir DIR --out-root DIR [--project-py PY] [--ruler-root DIR]
       [--dry_run]"""
import argparse
import json
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GROUPS = {"sum": ("src/ruler_pred.py", "mean,mean+g2f,quest"),
          "delim": ("src/delim_dev.py", "cobs,cobs+g2f,delim_cobs")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", required=True, choices=["1", "2", "3"])
    ap.add_argument("--models-dir", required=True)
    ap.add_argument("--out-root", required=True)
    ap.add_argument("--project-py", default=sys.executable)
    ap.add_argument("--ruler-root", default="/opt/ruler")
    ap.add_argument("--dry_run", action="store_true")
    a = ap.parse_args()
    plan = json.load(open(os.path.join(HERE, "plan_v1.json")))
    pc = plan["primary_cell"]
    mkey, L, bud, n = pc["model"], pc["length"], pc["budget"], pc["samples"]
    mdir = os.path.join(a.models_dir, mkey)
    data = os.path.join(a.out_root, "data", mkey, str(L))
    lines = ["#!/usr/bin/env bash", f"# generated by cluster/make_appendix_jobs.py --tier {a.tier} (v1.4 appendix, "
             "descriptive only)", "set -u", "export PYTORCH_CUDA_ALLOC_CONF=expandable_segments:True",
             f"[ -f {data}/prep_manifest.json ] || {{ echo 'run the main job script (data preparation) first'; exit 1; }}"]
    n_jobs = 0
    for g, (script, methods) in GROUPS.items():
        tag = f"t{a.tier}_n{n}_appendix-{g}"
        pred = os.path.join(a.out_root, "pred", mkey, str(L), f"budget{bud}", "b32", tag)
        lines.append(f"\n# ---- appendix group {g}: {methods} (run tag {tag})")
        for task in plan["tasks"]:
            lines.append(f"{shlex.quote(a.project_py)} {ROOT}/{script} --ruler {shlex.quote(a.ruler_root)} "
                         f"--model {shlex.quote(mdir)} --data_dir {data} --save_dir {pred} --task {task} "
                         f"--methods {methods} --budget {bud} --block 32 --limit {n} --strict-budget || exit 1")
            n_jobs += 1
    if a.dry_run:
        print(f"appendix (tier {a.tier}, primary cell {mkey} @ {L}, budget {bud}, n {n}): groups "
              f"{ {g: m for g, (_, m) in GROUPS.items()} }; prediction jobs {n_jobs}")
        return
    print("\n".join(lines))


if __name__ == "__main__":
    main()
